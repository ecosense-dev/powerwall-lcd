const char *app_tr(app_str_id_t id)
{
    if ((int)id < 0 || id >= STR_COUNT) {
        return "";
    }
    const char *const *tab = app_lang() == APP_LANG_EN ? S_EN : S_IT;
    return tab[id] ? tab[id] : "";
}

app_lang_t app_lang(void)
{
    app_config_t cfg;
    app_config_get(&cfg);
    return cfg.lang == APP_LANG_EN ? APP_LANG_EN : APP_LANG_IT;
}

void app_lang_set(app_lang_t lang)
{
    app_config_set_lang(lang);
}
